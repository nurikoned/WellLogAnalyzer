HF_REPO_ID     = "nurikoned/lithology-v64"
MODEL_FILENAME = "Ensemble_bundle.joblib"

RAW_LOGS       = ["GR", "RHOB", "RILD", "RILM", "RLL3", "DT", "SP", "SPOR"]
PHYSICS_FEATS  = ["VSH_LARIONOV", "PHI_D", "SW_ARCHIE"]
OPTIONAL_LOGS  = ["PE", "NPHI"]
