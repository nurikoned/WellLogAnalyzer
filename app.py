PEF_ALIASES    = ["PEF", "PE", "PEFZ", "PDPE", "PEF8"]
NPHI_ALIASES   = ["NPHI", "NEUT", "TNPH", "NPH", "CNL", "NPHI_LS"]

REQUIRED_LOGS     = ["GR", "RHOB", "RILD", "RILM", "RLL3", "DT", "SP", "SPOR"]
